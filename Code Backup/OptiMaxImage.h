#pragma once

#ifndef WIN32_LEAN_AND_MEAN
#define WIN32_LEAN_AND_MEAN
#endif

#include <windows.h>
#include <d3d11.h>
#include <wincodec.h>
#include <vector>
#include <string>

#pragma comment(lib, "windowscodecs.lib")

// =========================================================================
// IMAGE DECODE -> D3D11 TEXTURE
//
// Decodes PNG/JPG bytes into an ID3D11ShaderResourceView that ImGui can draw
// via ImGui::Image(). Uses WIC, which ships with Windows, so this adds no
// dependency - same reasoning as using WinHTTP/DPAPI elsewhere in the project.
//
// Everything is forced to 32bpp RGBA regardless of what the source file was,
// because that's the one layout the D3D11 backend and ImGui both expect.
// =========================================================================

namespace OptiMax {
    namespace Image {

        // Owns a decoded texture. Release() is idempotent, and the destructor
        // calls it, so a Texture member on a UI class can't leak the view.
        struct Texture {
            ID3D11ShaderResourceView* srv = nullptr;
            int width = 0;
            int height = 0;

            bool valid() const { return srv != nullptr; }

            void Release() {
                if (srv) { srv->Release(); srv = nullptr; }
                width = height = 0;
            }

            ~Texture() { Release(); }

            // Non-copyable: two owners would double-release the view.
            Texture() = default;
            Texture(const Texture&) = delete;
            Texture& operator=(const Texture&) = delete;
        };

        namespace detail {
            // One process-wide factory. WIC factories are expensive to create and
            // free-threaded, so creating one per decode would be wasteful.
            inline IWICImagingFactory* GetFactory() {
                static IWICImagingFactory* s_factory = nullptr;
                if (!s_factory) {
                    // The calling thread has already done CoInitializeEx (the UI
                    // thread does it in wWinMain).
                    HRESULT hr = CoCreateInstance(CLSID_WICImagingFactory, nullptr,
                        CLSCTX_INPROC_SERVER,
                        IID_PPV_ARGS(&s_factory));
                    if (FAILED(hr)) s_factory = nullptr;
                }
                return s_factory;
            }
        }

        // The largest edge kept for the top mip level. The Edit Profile picture is
        // drawn at 256 logical pixels, which is 512 real ones at 200% scaling and
        // 640 at 250%, so 512 would have meant upscaling - blurry - on a high-DPI
        // display. 1024 keeps a genuine 1:1-or-better source at every scale for
        // about 5.6MB of VRAM with the mip chain, while still stopping a 8192px
        // upload from costing a quarter of a gigabyte.
        static const UINT kMaxAvatarDimension = 1024;

        // Decodes an in-memory image into a texture. Returns false and leaves
        // outTexture untouched on any failure, so a corrupt or hostile avatar
        // download simply means "no picture", never a crash.
        //
        // A FULL MIP CHAIN IS BUILT, and that is the point of this function
        // rather than an afterthought. These textures are always drawn minified -
        // a 512px picture into a 44px circle. Sampling a single level at that
        // ratio reads four texels out of a quarter-million and produces the
        // crunchy, aliased result that looks like a low-resolution image even
        // when the source is sharp. Each level is generated by WIC's Fant
        // filter, which is a proper area average rather than a box decimation,
        // so the small sizes stay smooth.
        inline bool DecodeToTexture(ID3D11Device* device,
            const std::vector<unsigned char>& bytes,
            Texture& outTexture) {
            if (!device || bytes.empty()) return false;

            IWICImagingFactory* factory = detail::GetFactory();
            if (!factory) return false;

            IWICStream* stream = nullptr;
            IWICBitmapDecoder* decoder = nullptr;
            IWICBitmapFrameDecode* frame = nullptr;
            IWICFormatConverter* converter = nullptr;
            IWICBitmapScaler* baseScaler = nullptr;
            IWICBitmap* base = nullptr;          // decoded pixels, cached in memory
            ID3D11Texture2D* texture = nullptr;
            bool success = false;

            do {
                if (FAILED(factory->CreateStream(&stream))) break;
                if (FAILED(stream->InitializeFromMemory((BYTE*)bytes.data(), (DWORD)bytes.size()))) break;

                if (FAILED(factory->CreateDecoderFromStream(stream, nullptr,
                    WICDecodeMetadataCacheOnDemand, &decoder))) break;
                if (FAILED(decoder->GetFrame(0, &frame))) break;

                UINT srcW = 0, srcH = 0;
                if (FAILED(frame->GetSize(&srcW, &srcH))) break;

                // Sanity bound. A 16k x 16k image would be a 1GB allocation at
                // 32bpp; nothing legitimate needs that for an avatar.
                if (srcW == 0 || srcH == 0 || srcW > 8192 || srcH > 8192) break;

                if (FAILED(factory->CreateFormatConverter(&converter))) break;
                if (FAILED(converter->Initialize(frame, GUID_WICPixelFormat32bppRGBA,
                    WICBitmapDitherTypeNone, nullptr, 0.0,
                    WICBitmapPaletteTypeCustom))) break;

                // Top level size, aspect preserved.
                UINT w = srcW, h = srcH;
                UINT longEdge = (srcW > srcH) ? srcW : srcH;
                if (longEdge > kMaxAvatarDimension) {
                    double scale = (double)kMaxAvatarDimension / (double)longEdge;
                    w = (UINT)(srcW * scale);
                    h = (UINT)(srcH * scale);
                    if (w == 0) w = 1;
                    if (h == 0) h = 1;
                }

                // Cache the decoded pixels once. Every mip level pulls from this,
                // and without the cache each CopyPixels would re-run the PNG/JPEG
                // decoder from the top.
                IWICBitmapSource* topSource = converter;
                if (w != srcW || h != srcH) {
                    if (FAILED(factory->CreateBitmapScaler(&baseScaler))) break;
                    if (FAILED(baseScaler->Initialize(converter, w, h,
                        WICBitmapInterpolationModeFant))) break;
                    topSource = baseScaler;
                }
                if (FAILED(factory->CreateBitmapFromSource(topSource, WICBitmapCacheOnLoad, &base))) break;

                UINT mipCount = 1;
                for (UINT m = (w > h) ? w : h; m > 1; m >>= 1) ++mipCount;

                // Held together so every pointer handed to CreateTexture2D stays
                // alive until it returns.
                std::vector<std::vector<unsigned char>> levels(mipCount);
                std::vector<D3D11_SUBRESOURCE_DATA> init(mipCount);
                bool levelsOk = true;

                for (UINT i = 0; i < mipCount && levelsOk; ++i) {
                    UINT lw = w >> i, lh = h >> i;
                    if (lw == 0) lw = 1;
                    if (lh == 0) lh = 1;

                    const UINT stride = lw * 4;
                    levels[i].resize((size_t)stride * lh);

                    if (i == 0) {
                        levelsOk = SUCCEEDED(base->CopyPixels(nullptr, stride,
                            (UINT)levels[i].size(), levels[i].data()));
                    }
                    else {
                        IWICBitmapScaler* scaler = nullptr;
                        levelsOk = SUCCEEDED(factory->CreateBitmapScaler(&scaler));
                        if (levelsOk) {
                            levelsOk = SUCCEEDED(scaler->Initialize(base, lw, lh,
                                WICBitmapInterpolationModeFant))
                                && SUCCEEDED(scaler->CopyPixels(nullptr, stride,
                                    (UINT)levels[i].size(), levels[i].data()));
                            scaler->Release();
                        }
                    }

                    init[i].pSysMem = levels[i].data();
                    init[i].SysMemPitch = stride;
                    init[i].SysMemSlicePitch = 0;
                }
                if (!levelsOk) break;

                D3D11_TEXTURE2D_DESC desc = {};
                desc.Width = w;
                desc.Height = h;
                desc.MipLevels = mipCount;
                desc.ArraySize = 1;
                desc.Format = DXGI_FORMAT_R8G8B8A8_UNORM;
                desc.SampleDesc.Count = 1;
                desc.Usage = D3D11_USAGE_IMMUTABLE;
                desc.BindFlags = D3D11_BIND_SHADER_RESOURCE;

                if (FAILED(device->CreateTexture2D(&desc, init.data(), &texture)) || !texture) break;

                D3D11_SHADER_RESOURCE_VIEW_DESC srvDesc = {};
                srvDesc.Format = DXGI_FORMAT_R8G8B8A8_UNORM;
                srvDesc.ViewDimension = D3D11_SRV_DIMENSION_TEXTURE2D;
                srvDesc.Texture2D.MipLevels = mipCount;

                ID3D11ShaderResourceView* srv = nullptr;
                if (FAILED(device->CreateShaderResourceView(texture, &srvDesc, &srv)) || !srv) break;

                // Only now do we touch the caller's texture, so a failure halfway
                // through can't leave them with a half-updated object.
                outTexture.Release();
                outTexture.srv = srv;
                outTexture.width = (int)w;
                outTexture.height = (int)h;
                success = true;

            } while (false);

            if (texture)   texture->Release();
            if (base)      base->Release();
            if (baseScaler) baseScaler->Release();
            if (converter) converter->Release();
            if (frame)     frame->Release();
            if (decoder)   decoder->Release();
            if (stream)    stream->Release();

            return success;
        }

    } // namespace Image
} // namespace OptiMax
